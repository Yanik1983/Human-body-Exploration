const SPINE = [
  [1.575, -0.03], [1.5, -0.033], [1.43, -0.04], [1.36, -0.052], [1.28, -0.058],
  [1.2, -0.055], [1.12, -0.045], [1.05, -0.037], [1.0, -0.04], [0.96, -0.052],
];
export function spineZ(y) {
  if (y >= SPINE[0][0]) return SPINE[0][1];
  for (let i = 1; i < SPINE.length; i++) {
    const [y1, z1] = SPINE[i - 1], [y0, z0] = SPINE[i];
    if (y >= y0) {
      const t = (y - y0) / (y1 - y0);
      const s = t * t * (3 - 2 * t);
      return z0 + (z1 - z0) * s;
    }
  }
  return SPINE[SPINE.length - 1][1];
}

